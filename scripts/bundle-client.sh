#!/usr/bin/env bash
#
# Bundle the OpenWatchParty jellyfin-web client into a single embedded plugin.js.
#
# Upstream ships 26 IIFE modules that the dev loader (src/clients/jellyfin-web/plugin.js)
# pulls in one-by-one from /web/plugins/openwatchparty/... as ordered <script async=false>
# tags sharing global scope. Our JellyOps port instead serves ONE script from the plugin
# controller (GET /OpenWatchParty/ClientScript -> embedded OpenWatchParty.Plugin.Web.plugin.js),
# so there is no static plugin dir to stream the modules from.
#
# Because every module is a self-contained `(() => { ... window.OpenWatchParty ... })()`
# IIFE with no ES imports/exports, concatenating them in the loader's order is byte-for-byte
# equivalent to the ordered-script-tag behaviour (shared global scope, sequential execution).
# We then append the same bootstrap the loader ran (OWP.app.init()) plus the __loaded guard.
#
# Regenerate src/Plugin/Web/plugin.js after changing any vendored module under
# src/Plugin/Web/client/. The generated file is committed and embedded by the csproj.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CLIENT_DIR="$ROOT/src/Plugin/Web/client"
OUT="$ROOT/src/Plugin/Web/plugin.js"

# EXACT upstream justfile `client_js_files` order — do not reorder (later modules read
# globals published by earlier ones, e.g. lifecycle.js consumes OWP.constants/state/ui).
FILES=(
  state.js
  utils/time.js utils/video.js utils/misc.js utils/media.js utils/log.js
  ui/styles.js ui/indicators.js ui/toasts.js ui/cards.js ui/home.js ui/render.js
  playback/play.js playback/bind.js playback/sync.js
  chat/messages.js chat/input.js
  ws/send.js ws/auth.js
  ws/handlers/room.js ws/handlers/sync.js ws/handlers/playback.js ws/handlers/clock.js
  ws/connection.js
  app/lifecycle.js app/cleanup.js
)

for f in "${FILES[@]}"; do
  [ -f "$CLIENT_DIR/$f" ] || { echo "!! missing client module: $f" >&2; exit 1; }
done

{
  printf '// OpenWatchParty client bundle — GENERATED by scripts/bundle-client.sh. Do not edit.\n'
  printf '// Concatenation of the upstream jellyfin-web modules (client_js_files order),\n'
  printf '// served as a single script by GET /OpenWatchParty/ClientScript.\n'
  printf '(function () {\n'
  printf '  if (window.OpenWatchParty && window.OpenWatchParty.__loaded) return;\n'
  printf '  (window.OpenWatchParty = window.OpenWatchParty || {}).__loaded = true;\n'
  for f in "${FILES[@]}"; do
    printf '\n// ==== %s ====\n' "$f"
    cat "$CLIENT_DIR/$f"
  done
  # Same bootstrap the dev loader ran once every module was present.
  printf '\n// ==== bootstrap ====\n'
  printf 'try {\n'
  printf '  var OWP = window.OpenWatchParty;\n'
  printf '  if (OWP && OWP.app && typeof OWP.app.init === "function") OWP.app.init();\n'
  printf '} catch (err) { console.error("[OpenWatchParty] init error:", err); }\n'
  printf '})();\n'
} > "$OUT"

echo ">> Wrote $OUT ($(wc -l < "$OUT") lines, $(wc -c < "$OUT") bytes)"
